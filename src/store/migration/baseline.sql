    created_at bigint NOT NULL
);

ALTER TABLE public.voice_transcriptions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.voice_transcriptions_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
