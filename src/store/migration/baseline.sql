-- The voice's schema at 1.0.0, whole (docs/store.md, 「The migrations」).

CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA public;

CREATE TABLE public.voice_briefings (
    run_id bigint NOT NULL,
    chat_id bigint NOT NULL,
    message_id bigint,
    kind text DEFAULT 'full'::text NOT NULL,
    title text,
    voice_message_id bigint,
    sent_at bigint,
    seconds double precision,
    sound_path text,
    awaits_line bigint DEFAULT 0 NOT NULL,
    started_at bigint,
    finished_at bigint,
    rowid bigint GENERATED ALWAYS AS (run_id) STORED,
    synthesis_id bigint,
    plays bigint DEFAULT 1 NOT NULL
);

ALTER TABLE public.voice_briefings ALTER COLUMN run_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.voice_briefings_run_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.voice_encodings (
    id bigint NOT NULL,
    state text NOT NULL,
    from_wav text NOT NULL,
    sound_path text,
    created_at bigint NOT NULL
);

ALTER TABLE public.voice_encodings ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.voice_encodings_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.voice_events (
    id bigint NOT NULL,
    kind text NOT NULL,
    at bigint NOT NULL,
    data text NOT NULL
);

ALTER TABLE public.voice_events ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.voice_events_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.voice_names (
    written public.citext NOT NULL,
    ko text DEFAULT ''::text NOT NULL,
    en text DEFAULT ''::text NOT NULL,
    set_at bigint NOT NULL,
    rowid bigint NOT NULL
