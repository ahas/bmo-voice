ALTER TABLE public.voice_names ALTER COLUMN rowid ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.voice_names_rowid_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.voice_nodes (
    name text NOT NULL,
    "position" bigint NOT NULL,
    added_at bigint NOT NULL,
    rowid bigint NOT NULL
);

ALTER TABLE public.voice_nodes ALTER COLUMN rowid ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.voice_nodes_rowid_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
