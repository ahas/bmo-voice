CREATE TABLE public.voices (
    name text NOT NULL,
    checkpoint text NOT NULL,
    reference text NOT NULL,
    cfg double precision NOT NULL,
    steps bigint NOT NULL,
    current bigint DEFAULT 0 NOT NULL,
    set_at bigint NOT NULL,
    style text DEFAULT ''::text NOT NULL,
    seed bigint DEFAULT 0 NOT NULL,
    by_sentence bigint DEFAULT 0 NOT NULL,
    prompt_clip text DEFAULT ''::text NOT NULL,
    prompt_words text DEFAULT ''::text NOT NULL,
    prompt_en_clip text DEFAULT ''::text NOT NULL,
    prompt_en_words text DEFAULT ''::text NOT NULL,
    rowid bigint NOT NULL,
    language text DEFAULT 'ko'::text NOT NULL
);

ALTER TABLE public.voices ALTER COLUMN rowid ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.voices_rowid_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.voice_briefings
    ADD CONSTRAINT voice_briefings_pkey PRIMARY KEY (run_id);

ALTER TABLE ONLY public.voice_encodings
    ADD CONSTRAINT voice_encodings_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.voice_events
    ADD CONSTRAINT voice_events_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.voice_names
    ADD CONSTRAINT voice_names_pkey PRIMARY KEY (written);

ALTER TABLE ONLY public.voice_names
    ADD CONSTRAINT voice_names_rowid_key UNIQUE (rowid);

ALTER TABLE ONLY public.voice_nodes
    ADD CONSTRAINT voice_nodes_pkey PRIMARY KEY (name);

ALTER TABLE ONLY public.voice_nodes
    ADD CONSTRAINT voice_nodes_rowid_key UNIQUE (rowid);

ALTER TABLE ONLY public.voice_syntheses
    ADD CONSTRAINT voice_syntheses_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.voice_transcriptions
    ADD CONSTRAINT voice_transcriptions_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.voices
    ADD CONSTRAINT voices_pkey PRIMARY KEY (name);

ALTER TABLE ONLY public.voices
    ADD CONSTRAINT voices_rowid_key UNIQUE (rowid);

CREATE INDEX voice_briefings_message ON public.voice_briefings USING btree (chat_id, message_id);

CREATE INDEX voice_briefings_synthesis ON public.voice_briefings USING btree (synthesis_id);

CREATE INDEX voice_briefings_voice ON public.voice_briefings USING btree (chat_id, voice_message_id);

CREATE UNIQUE INDEX voice_syntheses_live_key ON public.voice_syntheses USING btree (key) WHERE ((key IS NOT NULL) AND (state <> 'failed'::text));

