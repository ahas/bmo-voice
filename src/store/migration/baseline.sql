CREATE TABLE public.voice_syntheses (
    id bigint NOT NULL,
    voice_name text NOT NULL,
    text text NOT NULL,
    emotion text,
    state text NOT NULL,
    duration_ms bigint,
    created_at bigint NOT NULL,
    spoken text,
    language text,
    key text,
    failure text,
    asked_by text
