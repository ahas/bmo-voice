-- Every table of the voice with its indexes, column for column in the shape the rows already kept read in, so a
-- table copied in keeps every column its readers name. A briefing's start and end are kept on its own row
-- (docs/store.md).

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE "voices" (
  "name" text,
  "checkpoint" text NOT NULL,
  "reference" text NOT NULL,
  "cfg" double precision NOT NULL,
  "steps" bigint NOT NULL,
  "current" bigint NOT NULL DEFAULT 0,
  "set_at" bigint NOT NULL,
  "style" text NOT NULL DEFAULT '',
  "seed" bigint NOT NULL DEFAULT 0,
  "by_sentence" bigint NOT NULL DEFAULT 0,
  "prompt_clip" text NOT NULL DEFAULT '',
  "prompt_words" text NOT NULL DEFAULT '',
  "prompt_en_clip" text NOT NULL DEFAULT '',
  "prompt_en_words" text NOT NULL DEFAULT '',
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("name")
);

CREATE TABLE "voice_names" (
  "written" citext,
  "ko" text NOT NULL DEFAULT '',
  "en" text NOT NULL DEFAULT '',
  "set_at" bigint NOT NULL,
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("written")
);

CREATE TABLE "voice_nodes" (
  "name" text,
  "position" bigint NOT NULL,
  "added_at" bigint NOT NULL,
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("name")
);

CREATE TABLE "voice_briefings" (
  "run_id" bigint GENERATED BY DEFAULT AS IDENTITY,
  "chat_id" bigint NOT NULL,
  "message_id" bigint,
  "kind" text NOT NULL DEFAULT 'full',
  "title" text,
  "voice_message_id" bigint,
  "sent_at" bigint,
  "seconds" double precision,
  "sound_path" text,
  "awaits_line" bigint NOT NULL DEFAULT 0,
  "started_at" bigint,
  "finished_at" bigint,
  rowid bigint GENERATED ALWAYS AS ("run_id") STORED,
  PRIMARY KEY ("run_id")
);

CREATE INDEX "voice_briefings_message" ON "voice_briefings" (chat_id, message_id);
CREATE INDEX "voice_briefings_voice" ON "voice_briefings" (chat_id, voice_message_id);
